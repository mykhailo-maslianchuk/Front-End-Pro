/*
Робота з атрибутами в DOM

Атрибути — це спеціальні додаткові дані, які зберігаються у HTML-тегах і описують властивості елементів.
Вони допомагають передати мета-інформацію про елемент, наприклад посилання, класи, ідентифікатори, типи, або інші параметри.

JavaScript через DOM дозволяє працювати з атрибутами, а саме:

  - Отримувати значення атрибутів (читати інформацію з HTML)
  - Змінювати існуючі атрибути (оновлювати значення)
  - Додавати нові атрибути (розширювати інформацію)
  - Видаляти атрибути (видаляти непотрібну інформацію)

Існує два основних типи атрибутів:

1) **Стандартні атрибути**
   Це атрибути, визначені в HTML-специфікації, наприклад:
   - `id` — унікальний ідентифікатор елемента
   - `class` — класи для стилізації
   - `href` — адреса посилання
   - `src` — адреса зображення або скрипта
   - `type`, `name`, `value` — для елементів форм і т.д.

2) **Користувацькі атрибути (data-атрибути)**
   HTML5 дозволяє створювати власні атрибути, які починаються з `data-`.
   Вони призначені для зберігання додаткових даних, які не впливають на вигляд чи поведінку елементів, але можуть бути використані у скриптах.

Переваги data-атрибутів:
- Не порушують валідацію HTML.
- Можна легко отримати і змінити через JavaScript.
- Зручно зберігати контекстні або динамічні дані.

**Як працювати з атрибутами в JavaScript?**

Основні методи DOM-елементів для роботи з атрибутами:

- `element.getAttribute(name)` — повертає значення атрибуту з ім'ям `name`. Якщо атрибуту немає — повертає `null`.

- `element.setAttribute(name, value)` — встановлює або змінює атрибут `name` на значення `value`. Якщо атрибуту не було — створює його.

- `element.hasAttribute(name)` — повертає `true`, якщо атрибут з ім'ям `name` існує, інакше `false`.

- `element.removeAttribute(name)` — видаляє атрибут з ім'ям `name`, якщо він існує.

Для роботи з data-атрибутами існує додаткова, дуже зручна властивість — `dataset`:

- `element.dataset` — об'єкт, де кожен data-атрибут доступний як властивість з ім'ям після "data-" у camelCase форматі.

  Наприклад:
  - `data-user-id` буде доступний як `element.dataset.userId`
  - `data-role` — як `element.dataset.role`

Через `dataset` можна отримувати і змінювати data-атрибути просто, як звичайні властивості об'єкта.

**Навіщо це потрібно?**

Атрибути дозволяють:

- Зберігати інформацію, що не відображається безпосередньо на сторінці, але потрібна для логіки (наприклад, ідентифікатори, статуси, ролі користувача).
- Керувати поведінкою елементів в залежності від їх атрибутів.
- Динамічно змінювати контент або параметри елементів через JavaScript.
- Зручно передавати інформацію між HTML і JS без складних структур.

---

**Приклади роботи з атрибутами:**
*/

// Знаходимо елемент по id
const link = document.getElementById("myLink");

// Отримуємо значення атрибутів
console.log("href атрибута:", link.getAttribute("href"));       // "https://example.com"
console.log("data-role атрибута:", link.getAttribute("data-role"));   // "admin"

// Змінюємо значення атрибута href
link.setAttribute("href", "https://google.com");
console.log("Новий href:", link.getAttribute("href"));  // "https://google.com"

// Додаємо новий атрибут target
link.setAttribute("target", "_blank");
console.log("Доданий target:", link.getAttribute("target"));  // "_blank"

// Видаляємо атрибут data-role
link.removeAttribute("data-role");
console.log("data-role після видалення:", link.getAttribute("data-role"));  // null

// Перевіряємо наявність атрибутів
console.log("Чи є href?", link.hasAttribute("href"));        // true
console.log("Чи є data-role?", link.hasAttribute("data-role"));   // false

// Робота з data-атрибутами через dataset
link.dataset.info = "some-info";
console.log("data-info через dataset:", link.dataset.info); // "some-info"





